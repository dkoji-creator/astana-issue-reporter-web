        t = j / max(1, cnt - 1)
        grow = int(round((g0 + (g1 - g0) * t) / 10)) * 10
        sellv = int(round(sell * mul * (1 + 0.6 * t)))
        seedv = int(round(seed * mul * (1 + 0.5 * t)))
