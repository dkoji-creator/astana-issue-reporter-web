def form_for(name, i):
    n = name.lower()
    for key, f in FORMS:
        if key in n:
            return f
    return ["orb", "flower", "crystal", "geode", "spiral", "star"][i % 6]


def hexcol(h, s, v):
    r, g, b = colorsys.hsv_to_rgb(h % 1, max(0, min(1, s)), max(0, min(1, v)))
    return "Color3.fromRGB(%d, %d, %d)" % (round(r * 255), round(g * 255), round(b * 255))


